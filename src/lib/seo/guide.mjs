import { JSON_LD_ITEMS, PAGE_FIELDS, REQUIRED_ITEMS, ROUTES, SITE_FIELDS } from "./contract.mjs";

const rules = (f) => [
  f.required ? "required" : "optional",
  f.min && f.max ? `${f.min} to ${f.max}${f.type === "list" ? " items" : " characters"}` : f.max ? `up to ${f.max}${f.type === "list" ? " items" : " characters"}` : "",
  f.options ? `one of: ${f.options.join(", ")}` : "",
].filter(Boolean).join("; ");
const rows = (fields, prefix = "") => Object.entries(fields).flatMap(([name, f]) => [
  `| \`${prefix}${name}\` | ${f.type} | ${rules(f)} | ${f.description}${f.example ? ` Example: \`${f.example}\`` : ""} |`,
  ...(f.fields ? rows(f.fields, `${prefix}${name}${f.type === "list" ? "[]" : ""}.`) : []),
]);
const table = (fields) => ["| Field | Type | Rules | What it is |", "|---|---|---|---|", ...rows(fields)].join("\n");

